// Helper to parse YouTube or YouTube Music links
export function parseYouTubeUrl(input) {
  if (!input || typeof input !== 'string') return null;
  const str = input.trim();

  // Handle music.youtube.com / www.youtube.com / youtu.be
  // Pattern 1: v=XXXXX
  const vMatch = str.match(/(?:music\.youtube\.com\/watch\?v=|youtube\.com\/watch\?v=|youtube\.com\/embed\/|youtu\.be\/|youtube\.com\/v\/)([^#&?]{11})/);
  if (vMatch && vMatch[1]) {
    return {
      type: 'video',
      id: vMatch[1],
      originalUrl: str
    };
  }

  // Pattern 2: playlist list=XXXX
  const listMatch = str.match(/[?&]list=([^#&?]+)/);
  if (listMatch && listMatch[1]) {
    return {
      type: 'playlist',
      id: listMatch[1],
      originalUrl: str
    };
  }

  // Pattern 3: Direct 11-char ID
  if (/^[a-zA-Z0-9_-]{11}$/.test(str)) {
    return {
      type: 'video',
      id: str,
      originalUrl: str
    };
  }

  // Otherwise it's a search query
  return {
    type: 'search',
    query: str,
    originalUrl: str
  };
}
